#!/usr/bin/env python3
"""
Automated Invariant Test Scaffolder
Parses '## 2. Invariants (Hard Rules)' across all documentation files in docs/
and generates an automated pytest test harness in tests/test_invariants.py.
"""
import re
import sys
from pathlib import Path
from typing import Dict, List, Tuple

# Ensure UTF-8 output
if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass

DOCS_DIR = Path("docs")
DEFAULT_OUTPUT = Path("tests/test_invariants.py")

INVARIANT_HEADER_RE = re.compile(r"^##\s+2\.\s+Invariants(?:\s+\(.*?\))?", re.IGNORECASE)
SECTION_HEADER_RE = re.compile(r"^##\s+", re.MULTILINE)
LIST_ITEM_RE = re.compile(r"^(?:[-*]|\d+\.)\s+(.+)$")


def slugify(text: str) -> str:
    slug = re.sub(r"[^a-zA-Z0-9]+", "_", text).strip("_").lower()
    return slug[:40] if len(slug) > 40 else slug


def extract_invariants(doc_path: Path) -> List[str]:
    """Extracts bulleted invariants from section 2 of a markdown file."""
    try:
        content = doc_path.read_text(encoding="utf-8")
    except Exception:
        return []

    lines = content.splitlines()
    in_invariants = False
    invariants = []

    for line in lines:
        if INVARIANT_HEADER_RE.match(line.strip()):
            in_invariants = True
            continue
        elif in_invariants and line.startswith("## "):
            # Reached next major section
            break
        elif in_invariants:
            match = LIST_ITEM_RE.match(line.strip())
            if match:
                invariant_text = match.group(1).strip()
                # Clean bold markdown wrappers if any
                clean_text = re.sub(r"^\*\*(.*?)\*\*:\s*", r"\1 - ", invariant_text)
                invariants.append(clean_text)

    return invariants


def collect_all_invariants() -> Dict[Path, List[str]]:
    """Collects invariants from all documentation files in docs/."""
    results = {}
    if not DOCS_DIR.exists():
        return results

    for md_file in sorted(DOCS_DIR.rglob("*.md")):
        # Skip decision records directory to focus on core specs
        if "docs/decisions" in md_file.as_posix() and md_file.name != "README.md":
            continue
        invariants = extract_invariants(md_file)
        if invariants:
            results[md_file] = invariants

    return results


def generate_test_file(invariants_map: Dict[Path, List[str]], output_path: Path) -> None:
    """Generates a pytest test file with test stubs for each invariant."""
    output_path.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        '#!/usr/bin/env python3',
        '"""',
        'Automated Invariant Verification Test Suite',
        'Auto-generated by scripts/generate_invariant_tests.py.',
        'Each test asserts an invariant defined in ## 2. Invariants (Hard Rules).',
        '"""',
        'import pytest',
        '',
    ]

    total_invariants = 0

    for doc_path, items in invariants_map.items():
        doc_rel = doc_path.as_posix()
        doc_slug = slugify(doc_path.stem)
        parent_slug = slugify(doc_path.parent.name)
        full_slug = f"{parent_slug}_{doc_slug}" if parent_slug and parent_slug != "docs" else doc_slug

        lines.append(f"# {'=' * 70}")
        lines.append(f"# Source: {doc_rel}")
        lines.append(f"# {'=' * 70}\n")

        for idx, item in enumerate(items, start=1):
            total_invariants += 1
            func_name = f"test_{full_slug}_invariant_{idx}"
            escaped_item = item.replace('"', '\\"')
            lines.append(f'def {func_name}():')
            lines.append(f'    """')
            lines.append(f'    Document: {doc_rel}')
            lines.append(f'    Invariant #{idx}:')
            lines.append(f'    {escaped_item}')
            lines.append(f'    """')
            lines.append(f'    # TODO: Implement concrete assertion once module code is developed')
            lines.append(f'    assert True')
            lines.append('')

    output_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"✨ Successfully generated {total_invariants} invariant test stubs in '{output_path.as_posix()}'!")


def main() -> int:
    import argparse
    parser = argparse.ArgumentParser(description="Automated Invariant Test Scaffolder")
    parser.add_argument("--output", "-o", default=str(DEFAULT_OUTPUT), help="Output test file path")
    parser.add_argument("--check", action="store_true", help="Audit if invariant test file is up to date")
    args = parser.parse_args()

    invariants_map = collect_all_invariants()
    total_found = sum(len(items) for items in invariants_map.values())
    print(f"🔍 Discovered {total_found} invariant(s) across {len(invariants_map)} specification documents.")

    output_path = Path(args.output)

    if args.check:
        if not output_path.exists():
            print(f"❌ Invariant test file '{output_path}' does not exist! Run without --check to generate.")
            return 1
        content = output_path.read_text(encoding="utf-8")
        missing = 0
        for doc, items in invariants_map.items():
            for idx, item in enumerate(items, start=1):
                doc_rel = doc.as_posix()
                if doc_rel not in content:
                    missing += 1
        if missing > 0:
            print(f"⚠️  Invariant tests out of date: {missing} invariant(s) not found in test suite.")
            return 1
        print("✨ Invariant test suite is completely up to date!")
        return 0

    generate_test_file(invariants_map, output_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
